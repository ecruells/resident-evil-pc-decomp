"""Convert generated GUIDE artwork to an embedded 256x16 4-bit title TIM.
Run from the repo root; requires ffmpeg/ffprobe on PATH. No Python packages.
"""
from pathlib import Path
import json, struct, subprocess

source = Path('infested/images/guide.png')
info = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-show_streams', '-of', 'json', str(source)]))['streams'][0]
w, h = info['width'], info['height']
rgba = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source), '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'])
points = [(x, y) for y in range(h) for x in range(w) if rgba[(y*w+x)*4+3] > 128]
x0, x1 = min(x for x,y in points), max(x for x,y in points)+1
y0, y1 = min(y for x,y in points), max(y for x,y in points)+1
height = 11
width = round((x1-x0)*height/(y1-y0))
assert width <= 240, 'Label exceeds texture page'
# Area-average alpha and luminance at the original menu letter height.
indices = [0]*(256*16)
left = (256-width)//2
for y in range(height):
 ya, yb = y0+y*(y1-y0)//height, y0+(y+1)*(y1-y0)//height
 for x in range(width):
  xa, xb = x0+x*(x1-x0)//width, x0+(x+1)*(x1-x0)//width
  total = 0
  for sy in range(ya,yb):
   for sx in range(xa,xb):
    q=(sy*w+sx)*4
    total += (sum(rgba[q:q+3])/3)*rgba[q+3]/255
  shade = round(total/((yb-ya)*(xb-xa))*15/255)
  indices[y*256+left+x] = max(0,min(15,shade))
palette = [0] + [(v | v<<5 | v<<10) for i in range(1,16) for v in [max(1,round(i*31/15))]]
pixels = bytes(indices[i] | indices[i+1]<<4 for i in range(0,len(indices),2))
tim = struct.pack('<IIIHHHH',16,8,44,0,480,16,1)+struct.pack('<16H',*palette)+struct.pack('<IHHHH',12+len(pixels),0,0,64,16)+pixels
Path('infested/images/guide.tim').write_bytes(tim)
Path('src/game/GuideTitleImage.h').write_text('// Generated by tools/gen_guide_title.py from infested/images/guide.png; do not edit.\n#pragma once\nalignas(4) static unsigned char kGuideTitleTim[] = {\n'+''.join('    '+','.join(str(b) for b in tim[i:i+24])+',\n' for i in range(0,len(tim),24))+'};\n')
print(f'GUIDE: {width}x{height} letters, embedded 256x16 TIM')
